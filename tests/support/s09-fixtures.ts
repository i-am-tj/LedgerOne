export function decimal(minor: bigint) {
  return `${minor / 100n}.${(minor % 100n).toString().padStart(2, "0")}`;
}
// Park–Miller generator, exact BigInt state. Reproducible and dependency-free;
// not cryptography and not a claim of exhaustive/random population coverage.
export function samples(seed: bigint, count: number) {
  let state = seed;
  return Array.from({ length: count }, () => {
    state = (state * 48271n) % 2147483647n;
    return (state % 90000n) + 1n;
  });
}
