import {
  Box,
  Building2,
  Car,
  ChartPie,
  CreditCard,
  Gem,
  Handshake,
  House,
  Landmark,
  Receipt,
  Repeat,
  Scale,
  ScrollText,
  Shield,
  Sparkles,
  Stamp,
  TrendingUp,
  Umbrella,
  Vault,
  Wallet,
  type LucideIcon,
} from "lucide-react";

const icons: Record<string, LucideIcon> = {
  landmark: Landmark,
  building: Building2,
  vault: Vault,
  repeat: Repeat,
  wallet: Wallet,
  pie: ChartPie,
  trending: TrendingUp,
  scroll: ScrollText,
  stamp: Stamp,
  shield: Shield,
  umbrella: Umbrella,
  gem: Gem,
  sparkles: Sparkles,
  home: House,
  car: Car,
  handshake: Handshake,
  box: Box,
  card: CreditCard,
  receipt: Receipt,
  scale: Scale,
};
export function wealthIcon(name: string): LucideIcon {
  return icons[name] ?? Box;
}
